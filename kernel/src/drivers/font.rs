pub const FONT_8X8: [[u8; 8]; 128] = build_font();

/// Render a single character to the framebuffer.
pub fn draw_char(fb: &mut Framebuffer, x: usize, y: usize, c: char, color: u32) {
    let glyph_idx = c as usize;
    if glyph_idx >= FONT_8X8.len() {
        return;
    }

    let glyph = &FONT_8X8[glyph_idx];

    for row in 0..8 {
        let bits = glyph[row];
        for col in 0..8 {
            if (bits & (1 << (7 - col))) != 0 {
                fb.put_pixel(x + col, y + row, color);
            }
        }
    }
}

/// Render a string of characters to the framebuffer.
#[allow(dead_code)]
pub fn draw_string(fb: &mut Framebuffer, x: usize, y: usize, s: &str, color: u32) {
    let mut current_x = x;
    for c in s.chars() {
        draw_char(fb, current_x, y, c, color);
        current_x += 8;
    }
}
